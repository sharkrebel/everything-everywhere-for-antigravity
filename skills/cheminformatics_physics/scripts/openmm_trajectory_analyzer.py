"""OpenMM and RDKit Molecular Dynamics Trajectory Analyzer.

Analyzes multi-frame molecular dynamics trajectories generated by OpenMM
(PDBReporter or multi-model PDB files) using native OpenMM and RDKit APIs
without external trajectory dependencies .

Calculates:
1. Heavy-atom RMSD time series vs reference/initial frame.
2. Per-atom Root-Mean-Square Fluctuation (RMSF).
3. Torsion Fingerprint Deviation (TFD) vs reference frame.
4. Conformer Butina clustering on pairwise RMSD matrices.
5. Export of representative centroid conformers to standard PDB format.
"""

import argparse
import json
import os
import sys

import numpy as np
import openmm.app as app
import openmm.unit as unit
import pandas as pd
from rdkit import Chem
from rdkit.Chem import AllChem, TorsionFingerprints, rdMolAlign
from rdkit.Geometry import Point3D
from rdkit.ML.Cluster import Butina

sys.stdout.reconfigure(line_buffering=True)

# Uniquely constraining 3D rigid-body rotation requires at least 3 points;
# smaller heavy-atom scaffolds (e.g., H2O, CH4, C2H6) fall back to all atoms.
MIN_RIGID_FIT_ATOMS = 3


def parse_args():
  parser = argparse.ArgumentParser(
      description=(
          'Analyze OpenMM MD trajectories using RDKit and native OpenMM tools.'
      )
  )
  parser.add_argument(
      '--trajectory',
      required=True,
      help='Path to multi-frame PDB trajectory file (from OpenMM PDBReporter).',
  )
  parser.add_argument(
      '--reference_pdb',
      required=False,
      default=None,
      help=(
          'Optional reference PDB structure. If omitted, uses frame 0 of'
          ' trajectory.'
      ),
  )
  parser.add_argument(
      '--smiles',
      required=False,
      default=None,
      help='Optional SMILES string of the ligand to ensure bond topology.',
  )
  parser.add_argument(
      '--output_dir',
      required=False,
      default='.',
      help='Directory to write output CSV, JSON, and PDB files.',
  )
  parser.add_argument(
      '--cluster_cutoff',
      type=float,
      default=0.5,
      help=(
          'RMSD distance cutoff (Angstroms) for Butina conformer clustering'
          ' (default: 0.5).'
      ),
  )
  parser.add_argument(
      '--export_centroids',
      type=int,
      default=3,
      help='Number of top cluster centroid conformers to export (default: 3).',
  )
  return parser.parse_args()


def load_trajectory_to_rdkit(pdb_trajectory_path, smiles=None):
  """Loads a multi-frame OpenMM PDB trajectory into a multi-conformer RDKit Mol."""
  pdb_traj = app.PDBFile(pdb_trajectory_path)
  num_frames = pdb_traj.getNumFrames()

  if num_frames == 0:
    raise ValueError(
        f'No frames found in trajectory file: {pdb_trajectory_path}'
    )

  # Determine base molecule topology
  if smiles:
    base_mol = Chem.MolFromSmiles(smiles)
    base_mol = Chem.AddHs(base_mol)
    AllChem.EmbedMolecule(base_mol, randomSeed=42)
  else:
    # Use frame 0 from PDB
    _ = pdb_traj.getPositions(asNumpy=True, frame=0).value_in_unit(
        unit.angstrom
    )
    # Write temporary single-frame PDB to preserve atom names and connectivity
    base_mol = Chem.MolFromPDBFile(pdb_trajectory_path, removeHs=False)
    if base_mol is None:
      raise ValueError(
          f'RDKit failed to parse base topology from: {pdb_trajectory_path}'
      )

  rd_mol = Chem.Mol(base_mol)
  rd_mol.RemoveAllConformers()

  num_atoms = rd_mol.GetNumAtoms()
  coords_list = []

  for frame_idx in range(num_frames):
    pos_angstrom = pdb_traj.getPositions(
        asNumpy=True, frame=frame_idx
    ).value_in_unit(unit.angstrom)
    coords_list.append(pos_angstrom)

    conf = Chem.Conformer(num_atoms)
    for atom_idx in range(num_atoms):
      p = pos_angstrom[atom_idx]
      conf.SetAtomPosition(
          atom_idx, Point3D(float(p[0]), float(p[1]), float(p[2]))
      )
    rd_mol.AddConformer(conf, assignId=True)

  return rd_mol, np.array(coords_list), pdb_traj.getTopology()


def compute_rmsd_time_series(rd_mol, ref_frame=0):
  """Computes heavy-atom RMSD time series vs a reference conformer."""
  num_frames = rd_mol.GetNumConformers()
  rmsds = []
  for f_idx in range(num_frames):
    rms = rdMolAlign.GetBestRMS(rd_mol, rd_mol, prbId=f_idx, refId=ref_frame)
    rmsds.append(rms)
  return np.array(rmsds)


def compute_rmsf(coords_array, atom_indices=None):
  """Computes per-atom Root-Mean-Square Fluctuation (RMSF) in Angstroms.

  Superimposes every trajectory frame onto frame 0 via Kabsch alignment before
  computing coordinate fluctuations so global rotation and translation do not
  contaminate internal atomic flexibility.

  Args:
    coords_array: Array of atomic coordinates with shape `(num_frames,
      num_atoms, 3)`.
    atom_indices: Optional sequence of atom indices used for superposition
      (defaults to all atoms).

  Returns:
    1D NumPy array of per-atom RMSF values in Angstroms.
  """
  coords = np.asarray(coords_array, dtype=np.float64)
  if coords.shape[0] <= 1:
    return np.zeros(coords.shape[1], dtype=np.float64)

  if atom_indices is not None and len(atom_indices) > 0:
    fit_idx = list(atom_indices)
  else:
    fit_idx = list(range(coords.shape[1]))
  ref_fit = coords[0, fit_idx]
  ref_center = np.mean(ref_fit, axis=0)
  p_ref = ref_fit - ref_center

  aligned = np.empty_like(coords)
  aligned[0] = coords[0]
  for f_idx in range(1, coords.shape[0]):
    cur_fit = coords[f_idx, fit_idx]
    cur_center = np.mean(cur_fit, axis=0)
    p_cur = cur_fit - cur_center
    cov = p_cur.T @ p_ref
    u, _, vt = np.linalg.svd(cov)
    det_sign = 1.0 if np.linalg.det(vt.T @ u.T) >= 0.0 else -1.0
    rot = vt.T @ np.diag([1.0, 1.0, det_sign]) @ u.T
    aligned[f_idx] = (coords[f_idx] - cur_center) @ rot.T + ref_center

  mean_coords = np.mean(aligned, axis=0)  # shape: (num_atoms, 3)
  rmsf = np.sqrt(np.mean(np.sum((aligned - mean_coords) ** 2, axis=-1), axis=0))
  return rmsf


def compute_tfd_time_series(rd_mol, ref_frame=0):
  """Computes Torsion Fingerprint Deviation (TFD) vs reference frame."""
  num_frames = rd_mol.GetNumConformers()
  tfd_list = []
  for f_idx in range(num_frames):
    try:
      val = TorsionFingerprints.GetTFDBetweenConformers(
          rd_mol, [f_idx], [ref_frame]
      )[0]
      tfd_list.append(float(val))
    except Exception:
      tfd_list.append(0.0)
  return np.array(tfd_list)


def cluster_trajectory_conformers(rd_mol, cutoff=0.5):
  """Clusters trajectory conformers using Butina clustering on pairwise RMSD matrix."""
  num_frames = rd_mol.GetNumConformers()
  dists = []
  for i in range(num_frames):
    for j in range(i):
      dists.append(rdMolAlign.GetBestRMS(rd_mol, rd_mol, prbId=i, refId=j))

  clusters = Butina.ClusterData(
      dists, num_frames, distThresh=cutoff, isDistData=True
  )
  return clusters


def main():
  args = parse_args()
  os.makedirs(args.output_dir, exist_ok=True)

  print(f'Loading trajectory from {args.trajectory}...')
  rd_mol, coords_array, topology = load_trajectory_to_rdkit(
      args.trajectory, args.smiles
  )
  num_frames = rd_mol.GetNumConformers()
  num_atoms = rd_mol.GetNumAtoms()
  print(f'Loaded {num_frames} frames ({num_atoms} atoms) into RDKit Mol.')

  # 1. Heavy-atom RMSD time series
  print('Computing heavy-atom RMSD time series...')
  rmsds = compute_rmsd_time_series(rd_mol, ref_frame=0)
  df_rmsd = pd.DataFrame(
      {'frame': np.arange(num_frames), 'rmsd_angstrom': np.round(rmsds, 4)}
  )
  rmsd_csv_path = os.path.join(args.output_dir, 'trajectory_rmsd.csv')
  df_rmsd.to_csv(rmsd_csv_path, index=False)
  print(f'Saved RMSD time series to {rmsd_csv_path}')

  # 2. Per-atom RMSF
  print('Computing per-atom RMSF...')
  heavy_indices = [
      i for i, a in enumerate(rd_mol.GetAtoms()) if a.GetAtomicNum() > 1
  ]
  fit_indices = (
      heavy_indices if len(heavy_indices) >= MIN_RIGID_FIT_ATOMS else None
  )
  rmsf = compute_rmsf(coords_array, atom_indices=fit_indices)
  atom_symbols = [a.GetSymbol() for a in rd_mol.GetAtoms()]
  df_rmsf = pd.DataFrame({
      'atom_index': np.arange(num_atoms),
      'symbol': atom_symbols,
      'rmsf_angstrom': np.round(rmsf, 4),
  })
  rmsf_csv_path = os.path.join(args.output_dir, 'trajectory_rmsf.csv')
  df_rmsf.to_csv(rmsf_csv_path, index=False)
  print(f'Saved per-atom RMSF to {rmsf_csv_path}')

  # 3. Torsion Fingerprint Deviation (TFD)
  print('Computing TFD time series...')
  tfd = compute_tfd_time_series(rd_mol, ref_frame=0)
  df_tfd = pd.DataFrame(
      {'frame': np.arange(num_frames), 'tfd': np.round(tfd, 5)}
  )
  tfd_csv_path = os.path.join(args.output_dir, 'trajectory_tfd.csv')
  df_tfd.to_csv(tfd_csv_path, index=False)
  print(f'Saved TFD time series to {tfd_csv_path}')

  # 4. Butina Conformer Clustering
  print(
      f'Clustering {num_frames} conformers at cutoff {args.cluster_cutoff} A...'
  )
  clusters = cluster_trajectory_conformers(rd_mol, cutoff=args.cluster_cutoff)
  print(f'Found {len(clusters)} distinct conformational clusters.')

  cluster_summary = []
  for cluster_idx, members in enumerate(clusters):
    centroid_frame = members[0]
    cluster_summary.append({
        'cluster_id': cluster_idx,
        'centroid_frame': centroid_frame,
        'num_members': len(members),
        'fraction_population': round(len(members) / num_frames, 4),
        'member_frames': list(members),
    })

  cluster_json_path = os.path.join(args.output_dir, 'trajectory_clusters.json')
  with open(cluster_json_path, 'w') as f:
    json.dump(cluster_summary, f, indent=2)
  print(f'Saved cluster summary to {cluster_json_path}')

  # 5. Export top centroid conformers
  exported_centroids = []
  for i in range(min(args.export_centroids, len(clusters))):
    c_info = cluster_summary[i]
    c_frame = c_info['centroid_frame']
    centroid_pdb_path = os.path.join(
        args.output_dir, f'cluster_{i}_centroid_frame_{c_frame}.pdb'
    )
    writer = Chem.PDBWriter(centroid_pdb_path)
    writer.write(rd_mol, confId=c_frame)
    writer.close()
    exported_centroids.append(centroid_pdb_path)
    print(
        f'Exported Cluster {i} centroid (frame {c_frame}) to'
        f' {centroid_pdb_path}'
    )

  # Summary report
  summary = {
      'trajectory_file': args.trajectory,
      'num_frames': num_frames,
      'num_atoms': num_atoms,
      'mean_rmsd_angstrom': float(np.mean(rmsds)),
      'max_rmsd_angstrom': float(np.max(rmsds)),
      'mean_rmsf_angstrom': float(np.mean(rmsf)),
      'max_rmsf_atom_index': int(np.argmax(rmsf)),
      'mean_tfd': float(np.mean(tfd)),
      'num_clusters': len(clusters),
      'top_cluster_population': float(
          cluster_summary[0]['fraction_population']
      ),
      'exported_centroid_pdbs': exported_centroids,
  }

  summary_path = os.path.join(
      args.output_dir, 'trajectory_analysis_summary.json'
  )
  with open(summary_path, 'w') as f:
    json.dump(summary, f, indent=2)

  print('\n=== Trajectory Analysis Summary ===')
  print(
      f'Mean Heavy-Atom RMSD: {summary["mean_rmsd_angstrom"]:.3f} A (Max:'
      f' {summary["max_rmsd_angstrom"]:.3f} A)'
  )
  print(f'Mean Atom RMSF: {summary["mean_rmsf_angstrom"]:.3f} A')
  print(
      f'Total Conformational Clusters: {summary["num_clusters"]} (Dominant'
      f' state: {summary["top_cluster_population"]*100:.1f}%)'
  )
  print('All analysis outputs generated successfully.')


if __name__ == '__main__':
  main()
